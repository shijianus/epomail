export const authDict: Record<AuthLang, Dict> = { zh, 'zh-Hant': zhHant, en, es, fr, nl };

export function createT(lang: AuthLang) {
  const table = authDict[lang] || en;
  return (key: string): string => table[key] ?? en[key] ?? key;
}

/** 管理后台 authI18n 覆盖 + 六语言字典的统一入口工厂 */
export function createTr(rawI18n: unknown, lang: AuthLang) {
  const blob = (rawI18n || {}) as Record<string, unknown>;
  const nested = Boolean(blob.zh || blob.en);
  const admin = (nested
    ? (blob[lang] as Dict) || (blob.en as Dict) || (blob.zh as Dict) || {}
    : blob) as Record<string, string>;
  const t = createT(lang);
  return (adminKey: string, dictKey?: string): string =>
    (typeof admin[adminKey] === 'string' && admin[adminKey]) || t(dictKey || adminKey);
}
