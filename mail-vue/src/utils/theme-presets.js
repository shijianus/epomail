export function getPresetName(preset, lang = 'zh') {
  if (!preset) return ''
  const l = lang || 'zh'
  if (preset.names && preset.names[l]) return preset.names[l]
  if (l === 'zh-Hant') return preset.nameZh || ''
  if (l !== 'zh') return preset.nameEn || preset.nameZh || ''
  return preset.nameZh || ''
}

export function getPresetDesc(preset, lang = 'zh') {
  if (!preset) return ''
  const l = lang || 'zh'
  if (preset.descs && preset.descs[l]) return preset.descs[l]
  if (l === 'zh-Hant') return preset.descZh || ''
  if (l !== 'zh') return preset.descEn || preset.descZh || ''
  return preset.descZh || ''
}

export function getWallpaperCssById(idOrUrl) {
  if (!idOrUrl || idOrUrl === 'none') return ''
  const preset = THEME_PRESETS.find(p => p.id === idOrUrl)
  const val = preset ? preset.url : idOrUrl
  if (!val) return ''
  if (val.startsWith('http://') || val.startsWith('https://') || val.startsWith('/')) {
    return `url('${val}')`
  }
  return val
}
