const languages = ['zh', 'zh-Hant', 'en', 'es', 'fr', 'nl'];

for (const lang of languages) {
  const filePath = path.join(i18nDir, `${lang}.js`);
  let content = fs.readFileSync(filePath, 'utf-8');

  // Update outdated step number strings
  for (const [key, transMap] of Object.entries(cleanStepReplacements)) {
    const val = transMap[lang];
    const regex = new RegExp(`(${key}:\\s*)["'][^"']+["']`, 'g');
    content = content.replace(regex, `$1"${val}"`);
  }

  // Inject new translations right before the closing "};"
  const newKeys = newTranslations[lang];
  let injectStr = '\n    // --- 场景裁决工作台专项词条 (严格六语言对称) ---\n';
  for (const [k, v] of Object.entries(newKeys)) {
    // Escape quotes if needed
    const escaped = v.replace(/"/g, '\\"');
    injectStr += `    ${k}: "${escaped}",\n`;
  }

  const closingIndex = content.lastIndexOf('};');
  if (closingIndex !== -1) {
    content = content.slice(0, closingIndex) + injectStr + content.slice(closingIndex);
    fs.writeFileSync(filePath, content, 'utf-8');
    console.log(`Updated ${lang}.js successfully.`);
  } else {
    console.error(`Could not find closing }; in ${lang}.js`);
  }
}
