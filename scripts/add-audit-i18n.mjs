for (const lang of ['zh', 'zh-Hant', 'en', 'es', 'fr', 'nl']) {
  const filePath = path.join(i18nDir, `${lang}.js`);
  let content = fs.readFileSync(filePath, 'utf8');
  
  // If already contains auditReport, skip
  if (content.includes('auditReport:')) {
    console.log(`${lang}.js already has auditReport`);
    continue;
  }
  
  const entries = newTranslations[lang];
  let snippet = '\n    // --- 操作报告与风控管理 (Audit & Risk Reports) ---\n';
  for (const [k, v] of Object.entries(entries)) {
    snippet += `    ${k}: ${JSON.stringify(v)},\n`;
  }
  
  const markerIndex = content.indexOf('manageUrlBadge:');
  if (markerIndex !== -1) {
    const braceIndex = content.indexOf('};', markerIndex);
    if (braceIndex !== -1) {
      content = content.slice(0, braceIndex) + snippet + content.slice(braceIndex);
      fs.writeFileSync(filePath, content, 'utf8');
      console.log(`Updated ${lang}.js successfully!`);
    } else {
      console.error(`Could not find closing }; after manageUrlBadge in ${lang}.js`);
    }
  } else {
    console.error(`Could not find manageUrlBadge in ${lang}.js`);
  }
}
